"""Turns the REAL src\\hlsl\\NewVegas\\Shaders\\Includes\\PBR.hlsl into C++ (pbr_gen.h) for the furnace harness, so the test
runs the shipped shading code, not a hand copy. Only mechanical rewrites: HLSL scalar swizzles to float3(...), float literals
to f-suffixed ones, and 'const float3 x = dot(...)' kept (the shim splats); register bindings dropped (constants become globals).
Usage: py -3.11 -I gen_pbr_cpp.py [source PBR.hlsl] [output .h] [C++ namespace]   (default: this tree's PBR.hlsl -> pbr_gen.h)"""
import os, re, sys
here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "..", "src", "hlsl", "NewVegas", "Shaders", "Includes", "PBR.hlsl")
s = open(src, encoding="utf-8").read()
s = re.sub(r"#if defined\(__INTELLISENSE__\).*?#endif", "", s, flags=re.S)
s = re.sub(r"\s*:\s*register\(\w+\)", "", s)                           # float4 X : register(c223) -> a global
s = re.sub(r"float\(([-0-9.ef]+)\)\.(rrr|xxx)", r"float3(\1)", s)       # float(0.04).rrr
s = re.sub(r"\(([-0-9.ef]+)\)\.(rrr|xxx)", r"float3(\1)", s)            # (1.0).xxx
s = re.sub(r"(?<![\w.])(\d+\.\d*|\.\d+)(?![\w.f])", r"\1f", s)          # 0.5 -> 0.5f
s = s.replace(".ff", ".f")
s = re.sub(r"\)\.r", ").x", s)                                     # Fresnel(...).r
s = re.sub(r"\)\.r(?![a-z])", ").x", s)
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(here, "pbr_gen.h")
if len(sys.argv) > 3: s = "namespace %s {\n%s\n}\n" % (sys.argv[3], s)
open(out, "w", encoding="utf-8").write("// GENERATED by gen_pbr_cpp.py from Shaders\\Includes\\PBR.hlsl -- do not edit\n#pragma once\n#include \"hlsl_shim.h\"\n" + s)
print("wrote", out)
